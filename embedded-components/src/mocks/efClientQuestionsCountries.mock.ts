const question = (
  id: string,
  description: string,
  responseSchema: object,
  extra: object = {}
) => ({
  content: [{ description, label: description, locale: 'en-US' }],
  defaultLocale: 'en-US',
  description,
  id,
  responseSchema,
  ...extra,
});

const countries = (maxItems: number) => ({
  items: { enum: QUESTION_COUNTRY_OPTIONS, type: 'string' },
  maxItems,
  minItems: 1,
  type: 'array',
});

const date = {
  items: { format: 'date', pattern: 'yyyy-MM-dd', type: 'string' },
  maxItems: 1,
  minItems: 1,
  type: 'array',
};

